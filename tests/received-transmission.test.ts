import {arabicSearchKey} from '../legacy/lib/arabicSearch';
import assert from 'node:assert/strict';
import {extractTeacherTransmission,receivedPersonalChain} from '../legacy/lib/receivedTransmission';
import {assembleIjazah} from '../legacy/lib/assembleIjazah';
import {compactReadingCount,ijazahCoverage} from '../legacy/lib/ijazahCoverage';
import {personalIssuerName} from '../legacy/lib/issuerNames';
const personal='كَمَا أَخَذْتُهُ عن الشيخ الأول، عن شيخ ثان، عن الإمام الثالث، عن من تقدم من الأئمة إلى رسول الله صلى الله عليه وسلم';
const conclusion='هذا وأوصيه بتقوى الله والعمل بما علم';
const source=`【بيان القراءة:رواية قالون】\nالمقدمة وكلمات الإجازة. ${personal}، عن بقية الناقلين.\n${conclusion}`;
const transmission=extractTeacherTransmission(source,personal,[conclusion]);
assert.ok(transmission.startsWith('عن الشيخ الأول'));
assert.ok(!transmission.includes('المقدمة'));
assert.ok(!transmission.includes(conclusion));
const copy=receivedPersonalChain('المجيز المباشر',transmission);
assert.ok(copy.startsWith('كما أخذته عن الشيخ المجيز المباشر، عن الشيخ الأول'));
assert.equal(source.includes(personal),true,'The original source stays unchanged');
assert.throws(()=>extractTeacherTransmission('unstructured text'));
const assembled=assembleIjazah({qariId:'nafi',rawi:'قالون',personalChain:copy,junction:'jazari',chainMode:'complete'},[]);
assert.equal(assembled.missing.length,0);
assert.equal(assembled.chain.split('عن الشيخ الأول').length-1,1,'Do not append shared route fragments to a complete received chain');
assert.ok(arabicSearchKey(assembled.heading).includes('الشاطبية'));
assert.equal(compactReadingCount([{qariId:'nafi',rawi:'قالون'},{qariId:'nafi',rawi:'ورش'}]),'١ قراءة');
assert.equal(ijazahCoverage([{qariId:'nafi',rawi:'قالون'}]).standalone,1);
assert.equal(personalIssuerName('عُمَر مُحمّد قُريشي','','عمر'),'عُمَر مُحمّد قُريشي');
assert.equal(personalIssuerName('Login','Full printed name','Old'),'Full printed name');
console.log('PASS: received-chain extraction, direct issuer prefix, no duplicate route chains, paired reading counts and canonical issuer names');
