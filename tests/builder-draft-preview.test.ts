import assert from 'node:assert/strict';
import {builderDraftPreviewNodes,builderPreview,type BuilderChain} from '../legacy/lib/bookBuilder';
const people=[{id:'j',name:'الإمام ابن الجزري',display_name:'ابن الجزري',archived:false},{id:'s',name:'أبي محمد عبد الله المعروف بـ سبط الخياط',display_name:'سبط الخياط',archived:false},{id:'q',name:'القطيعي',display_name:'القطيعي',archived:false},{id:'m',name:'المطوعي',display_name:'المطوعي',archived:false}];
const draft=[['s','q'],['s','m']].map(branch=>branch.map(id=>({personId:id,name:people.find(p=>p.id===id)!.name,source:id!=='s'})));
const before=JSON.stringify({people,draft});
const prepared=builderDraftPreviewNodes(people,draft);
assert.equal(prepared.branches[0][0].person_id,prepared.branches[1][0].person_id);
const book={id:'book',title:'الدرة',author_id:'j',archived:false};
const parent={branches:[[]]} as unknown as BuilderChain;
const route={branches:prepared.branches,continuation:'عن إدريس، عن خلف'} as BuilderChain;
const text=builderPreview(book,parent,route,prepared.people).text;
assert.ok(text.includes('(ح). وقرأ سبط الخياط أيضًا على المطوعي.'));
assert.ok(!text.includes('وقرأ ابن الجزري'));
assert.equal(text.match(/عن الإمام ابن الجزري/g)?.length,1);
assert.equal(text,builderPreview(book,parent,{...route,branches:draft.map(b=>b.map(n=>({person_id:n.personId,route_source:n.source})))},people).text,'unsaved preview equals saved library rendering');
assert.equal(JSON.stringify({people,draft}),before);
const typed=builderDraftPreviewNodes(people,[[{name:'نفس الاسم',source:false}],[{name:'نفس الاسم',source:false}]]);
assert.notEqual(typed.branches[0][0].person_id,typed.branches[1][0].person_id,'unselected names are not silently merged');
console.log('Draft preview retains shared identities, short names and matches saved rendering: PASS');
