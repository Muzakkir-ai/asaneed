import assert from 'node:assert/strict';
import {resolveBuilderPrefix,UBAYDI_BRIDGE_TITLE} from '../legacy/lib/builderPrefix';
import {builderPreview,type BuilderChain} from '../legacy/lib/bookBuilder';
const personal='عن الشيخ عبد الله بن محمد، عن إبراهيم العُبيدي';
const bridge={id:'bridge',title:UBAYDI_BRIDGE_TITLE,body:'عن راو أول، عن راو ثان (ح). وقرأ راو آخر على الإمام محمد بن محمد الجزري'};
const resolved=resolveBuilderPrefix(personal,[bridge]);
assert.equal(resolved.text,personal+'، '+bridge.body);
assert.equal(resolved.sourceId,'bridge');
assert.equal(resolved.text.match(/إبراهيم العُبيدي/gu)?.length,1);
assert.ok(resolved.text.includes('(ح). وقرأ'),'saved branch text is preserved');
const already=personal+'، '+bridge.body;
assert.equal(resolveBuilderPrefix(already,[bridge]).text,already,'do not add the bridge again');
assert.throws(()=>resolveBuilderPrefix(personal,[]),/غير متاحة/u);
assert.throws(()=>resolveBuilderPrefix(personal,[bridge,{...bridge,id:'other'}]),/اختر التتمة/u);
assert.equal(resolveBuilderPrefix(personal,[bridge,{...bridge,id:'other'}],'other').sourceId,'other');
assert.throws(()=>resolveBuilderPrefix(personal,[bridge],'not-visible'),/غير متاحة/u);
assert.throws(()=>resolveBuilderPrefix(personal,[{...bridge,body:'عن رجل لا يوجد بعده السند المطلوب'}]),/لا تصل/u);
assert.throws(()=>resolveBuilderPrefix('عن شيخ لم يذكر نهاية السند هنا', [bridge]));
assert.throws(()=>resolveBuilderPrefix(personal,[{...bridge,body:personal+'، '+bridge.body}]),/تكرار/u);
const people=['صاحب الكتاب','راو قبل الكتاب','صاحب الطريق'].map((name,i)=>({id:String(i),name,display_name:'',archived:false}));
const book={id:'book',author_id:'0',title:'كتاب',archived:false};
const parent={branches:[[{person_id:'1',route_source:false}]]} as BuilderChain;
const route={branches:[[{person_id:'2',route_source:true}]],continuation:'عن الراوي، عن الإمام، عن الصحابي'} as BuilderChain;
const preview=builderPreview(book,parent,route,people,resolved.text);
assert.ok(preview.text.startsWith(personal+'، '+bridge.body));
assert.ok(preview.text.indexOf('الجزري')<preview.text.indexOf('صاحب الكتاب'));
assert.equal(preview.text.match(/صاحب الكتاب/gu)?.length,1);
assert.deepEqual(preview.sources,['صاحب الطريق']);
console.log('Saved Ubaydi bridge, branch preservation, explicit ambiguity, missing-source denial and full custom-route assembly: PASS');
