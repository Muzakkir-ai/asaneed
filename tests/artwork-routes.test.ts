import {routeBookDirectory,labelRouteBookArtwork} from '../legacy/lib/routeBookArtwork';
import assert from 'node:assert/strict';
import {numberedArtworkPath,svgDimensions} from '../legacy/lib/artworkCatalog';
import {svgReadingParts,riwayahSvgWidthMm,riwayahSvgUrl} from '../legacy/lib/riwayahSvgHeading';
import {assembleIjazah} from '../legacy/lib/assembleIjazah';
import {canUsePersonalSanad} from '../legacy/lib/personalSanadValidation';
assert.equal(numberedArtworkPath('svg/mashaykh/zaka/name.svg'),null);
assert.equal(numberedArtworkPath('svg/books/01/name.svg'),null);
assert.equal(numberedArtworkPath('svg/mashaykh/01/heading.svg'),null);
assert.equal(numberedArtworkPath('svg/mashaykh/01/../../evil.svg'),null);
assert.equal(numberedArtworkPath('svg/mashaykh/03/line-02.svg')?.number,'03');
assert.deepEqual(svgDimensions('<svg viewBox="0 0 150 44.15"></svg>'),{width:150,height:44.15});
assert.throws(()=>svgDimensions('<svg viewBox="0 0 0 2"/>'));
const artwork=[{kind:'turuq' as const,number:'03',line:'heading' as const,path:'svg/turuq/03/heading.svg',label:'المصباح عن الفيل',width:250,height:30}];
const heading='رواية حفص عن الإمام عاصم الكوفي من طريق المصباح عن الفيل';
assert.equal(svgReadingParts(heading,{catalog:artwork})?.at(-1),artwork[0].path);
assert.equal(svgReadingParts(heading,{catalog:[]}),null);
assert.equal(riwayahSvgWidthMm(artwork[0].path,artwork),250/30*8.445);
assert.equal(riwayahSvgUrl(artwork[0].path,'https://example.test/pinned'),'https://example.test/pinned/svg/turuq/03/heading.svg');
const chain='كما أخذته عن شيوخي بهذا الطريق الخاص إلى رسول الله صلى الله عليه وسلم '.repeat(3);
const holding={qariId:'asim',rawi:'حفص',personalChain:chain,junction:'ubaydi',tariqNumber:'03',tariqName:'المصباح عن الفيل'};
const custom=assembleIjazah(holding,[]);
assert.equal(custom.missing.length,0);
assert.ok(custom.chain.includes(chain.trim()));
assert.ok(custom.heading.endsWith('من طريق المصباح عن الفيل'));
assert.ok(!custom.chain.includes('الشاطبية'));
assert.ok(canUsePersonalSanad(holding));
assert.ok(assembleIjazah({...holding,personalChain:'قصير'},[]).missing.length);
assert.ok(assembleIjazah({...holding,tariqNumber:'',tariqName:''},[]).missing.length,'Default route still requires its shared chain sections');
console.log('PASS: numbered paths, viewBox validation, custom route SVG matching, pinned URLs, separate complete chains, unchanged default validation');

const bookArtwork={kind:'books' as const,number:'03',line:'heading' as const,path:'svg/books/03/heading.svg',label:'المستنير',width:250,height:30};
assert.equal(svgReadingParts(heading.replace('المصباح عن الفيل','المستنير وهي من طرق طيبة النشر'),{catalog:[bookArtwork]})?.at(-1),bookArtwork.path);

const separated=assembleIjazah({...holding,tariqName:'المستنير — طريق ابن الخشنام',wordingId:'words'},[{id:'words',title:'كلمات',body:'أجزته {{القراءة/الرواية}}',sectionType:'wording'}]);
assert.ok(separated.heading.endsWith('من طريق المستنير'));
assert.ok(!separated.heading.includes('طيبة'));
const unvocalized=separated.chain.normalize('NFKC').replace(/[\u064b-\u065f\u0670\u0640]/gu,'');
assert.ok(unvocalized.includes('، وهي من طرق طيبة النشر'));
assert.ok(!separated.chain.includes('ابن الخشنام'));

const numberedBooks=[{title:'المستنير',artwork_number:'01',archived:false},{title:'مؤرشف',artwork_number:'02',archived:true}];
assert.deepEqual(routeBookDirectory(numberedBooks),[{number:'01',name:'المستنير',path:'svg/turuq/01/heading.svg'}]);
const unlabeled={...artwork[0],number:'01',path:'svg/turuq/01/heading.svg',label:''};
assert.equal(labelRouteBookArtwork([unlabeled],numberedBooks)[0].label,'المستنير');
assert.equal(labelRouteBookArtwork([bookArtwork],numberedBooks)[0].label,bookArtwork.label,'books namespace unaffected');
assert.equal(unlabeled.label,'','catalog inputs immutable');
