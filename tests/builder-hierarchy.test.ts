import assert from 'node:assert/strict';
import {builderPersonRoutes} from '../legacy/lib/builderPersonRoutes';
import {builderRouteName,type BuilderLibrary,type BuilderChain} from '../legacy/lib/bookBuilder';
import {sectionDisplayTitle} from '../legacy/lib/sectionDisplayTitle';
const book={id:'book',title:'الشاطبية',author_id:'author',archived:false};
const parent={id:'parent',book_id:'book',kind:'book',archived:false,branches:[[{person_id:'teacher',route_source:false}]]} as BuilderChain;
const route={id:'route',book_id:'book',book_chain_id:'parent',kind:'route',title:'مسار محفوظ',upper_route_name:'الطريق الأعلى المدخل',branch_route_name:'الفرع المدخل',reading_scope:'sughra',qari_id:'nafi',rawi:'قالون',archived:false,branches:[[{person_id:'upper',route_source:true,source_level:'upper'},{person_id:'branch',route_source:true,source_level:'branch'},{person_id:'legacy',route_source:true}]]} as BuilderChain;
const lib={books:[book],chains:[parent,route],people:[],suggestions:[],continuations:{}} as BuilderLibrary;
assert.deepEqual(builderPersonRoutes(lib,'upper')[0].levels,['upper']);
assert.deepEqual(builderPersonRoutes(lib,'branch')[0].levels,['branch']);
assert.deepEqual(builderPersonRoutes(lib,'legacy')[0].levels,['unclassified'],'never infer old source levels');
assert.ok(builderPersonRoutes(lib,'author')[0].author);
assert.equal(builderPersonRoutes(lib,'teacher').length,1,'book-sanad members inherit route membership');
assert.equal(builderPersonRoutes(lib,'same-name-other-id').length,0,'membership is identity based');
assert.equal(builderPersonRoutes({...lib,chains:[parent,{...route,archived:true}]},'upper').length,0);
assert.equal(builderRouteName(book,route),'الشاطبية — الطريق الأعلى المدخل — الفرع المدخل — مسار محفوظ');
assert.equal(builderRouteName(book,{...route,upper_route_name:'',branch_route_name:''}),'الشاطبية — مسار محفوظ');
assert.ok(!sectionDisplayTitle('CHAIN:nafi:ورش').includes('CHAIN:'));
assert.ok(sectionDisplayTitle('CHAIN:nafi:sahaba').includes('الصحابة'));
assert.ok(sectionDisplayTitle('CHAIN:asim:prophet').includes('النبي'));
assert.equal(sectionDisplayTitle('مقدمة خاصة'),'مقدمة خاصة');
console.log('Route hierarchy, stable-ID membership, unclassified legacy roles and Arabic display labels: PASS');
