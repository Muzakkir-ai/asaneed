import assert from 'node:assert/strict';
import {renderSanadSequence,renderBranchedSanad,sanadSubjectName} from '../legacy/lib/branchedSanad';
const names:Record<string,string>={j:'ابن الجزري',a:'أبي محمد سبط الخياط',b:'أبي المعالي ثابت',c:'الواسطي',q:'القطيعي',d:'أبي الفضل الشريف',e:'الكارزيني',m:'المطوعي',i:'إدريس',k:'خلف'};
const name=(id:string)=>names[id];const subject=(id:string)=>id==='a'?'سبط الخياط':sanadSubjectName(name(id));
const first=['j','a','b','c','q'],second=['j','a','d','e','m'];
const input=JSON.stringify([first,second]);
const text=renderBranchedSanad([first,second],name,subject,'','عن إدريس، عن خلف، عن بقية السند');
assert.equal(text,'عن ابن الجزري، عن أبي محمد سبط الخياط، عن أبي المعالي ثابت، عن الواسطي، عن القطيعي (ح). وقرأ سبط الخياط أيضًا على أبي الفضل الشريف، عن الكارزيني، عن المطوعي. وقرأ القطيعي والمطوعي على إدريس، عن خلف، عن بقية السند');
assert.equal(JSON.stringify([first,second]),input);
const structured=renderBranchedSanad([[...first,'i','k'],[...second,'i','k']],name,subject,'السند الشخصي','عن بقية السند');
assert.equal(structured.match(/السند الشخصي/g)?.length,1);
assert.equal(structured.match(/إدريس/g)?.length,1);
assert.ok(structured.endsWith('على إدريس، عن خلف، عن بقية السند'));
assert.equal(sanadSubjectName('أبي محمد'),'أبو محمد');
assert.equal(sanadSubjectName('أبي محمد عبد الله المعروف بـ سبط الخياط'),'سبط الخياط');
const complex=renderBranchedSanad([first,['j','a','d','b','m']],name,subject,'','عن إدريس');
assert.ok(complex.includes('\n\n(ح)\n\n'),'overlapping interiors retain complete branches');
const unrelated=renderBranchedSanad([['q'],['m']],name,subject,'','عن إدريس');
assert.ok(unrelated.includes('\n\n(ح)\n\n'),'no unproven common pivot');
assert.equal(renderBranchedSanad([first],name,subject,'','عن إدريس'),'عن ابن الجزري، عن أبي محمد سبط الخياط، عن أبي المعالي ثابت، عن الواسطي، عن القطيعي، عن إدريس');
assert.ok(renderBranchedSanad([first,second],name,subject,'','نص حر').includes('\n\n(ح)\n\n'));
console.log('Branch change wording, structured/textual convergence, source preservation and safe fallbacks: PASS');

const repeated=[['j','b','a','q','i'],['j','c','a','m','i']];
const repeatedText=renderBranchedSanad(repeated,name,subject,'','عن خلف');
assert.equal(repeatedText.match(/سبط الخياط/g)?.length,1);
assert.ok(repeatedText.includes('وهما قرآ على أبي محمد سبط الخياط'));
assert.ok(repeatedText.includes('عن القطيعي، والمطوعي، وهما قرآ على إدريس'));
assert.ok(!repeatedText.includes('(ح)'));
const mixed=renderBranchedSanad([['j','b','a','c','q'],['j','d','a','e','m']],name,subject,'','عن إدريس');
assert.ok(mixed.includes('وهما قرآ على أبي محمد سبط الخياط'));
assert.ok(mixed.includes('(ح). وقرأ سبط الخياط أيضًا على'));

assert.equal(renderSanadSequence(['عن الشيخ مُحَمَّد،','عن عن إبراهيم العُبيدي.']),'عن الشيخ مُحَمَّد، عن إبراهيم العُبيدي');
