import assert from 'node:assert/strict';
import {matchesArabic,arabicSearchKey} from '../src/lib/arabicSearch';
import {sessionCall,setSessionRefresher,SessionExpiredError} from '../src/lib/sessionRecovery';
let expired=0;
(globalThis as any).window={dispatchEvent:(e:Event)=>{if(e.type==='asaneed-session-expired')expired++;}};
assert.ok(matchesArabic('مُحَمَّد مُذَكِّر','محمد مذكر'));
assert.ok(matchesArabic('إِبْرَاهِيمُ العُبَيدِيّ','ابراهيم العبيدي'));
assert.ok(matchesArabic('٠١٢٦-١٠٠٢','0126-1002'));
assert.ok(matchesArabic('0126-1002','٠١٢٦-١٠٠٢'));
assert.equal(arabicSearchKey(' ذَكَاءُ  الله '),'ذكاء الله');
let refreshes=0,calls=0;
setSessionRefresher(async()=>{refreshes++;});
const recovered=sessionCall(async()=>{calls++;if(calls===1)throw Error('API call failed (401): Unauthorized');return 'certificate';});
assert.equal(await recovered({}),'certificate');
assert.equal(refreshes,1);assert.equal(calls,2);assert.equal(expired,0);
const denied=sessionCall(async()=>{throw Error('Permission denied (403)');});
await assert.rejects(()=>denied({}),/403/);assert.equal(refreshes,1);
const expiredCall=sessionCall(async()=>{throw Error('API call failed (401): Unauthorized');});
await assert.rejects(()=>expiredCall({}),SessionExpiredError);
assert.equal(expired,1);
setSessionRefresher(undefined);
console.log('PASS session/search: 401 refresh then retry, clear expired state, no retry on 403, preserved Arabic names and both numeral styles.');
