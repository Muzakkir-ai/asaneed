import assert from 'node:assert/strict';
import endpoint from '../src/api/adminBackup';
import {BACKUP_TABLES} from '../src/lib/backupManifest';
import {rows,operations} from './mockDb';
const id=(n:number)=>'00000000-0000-4000-8000-'+String(n).padStart(12,'0');
const admin={id:id(1),email:'admin@example.test',name:'Admin',authUserId:'account',role:'Admin',active:true};
rows.appUsers=[admin];
rows.additionalShaykhs=[{id:id(2),name:'ذَكَاءُ الله'}];
rows.asaneed=[{id:id(3),title:'سند',additionalShaykh:id(2),chain:'السند',qiraah:[],certificates:[id(4)]}];
rows.certificates=[{id:id(4),studentName:'مُحَمَّد',additionalShaykh:id(2),sanad:[id(3)],registrationNumber:'0126-0201',certificateNumber:99}];
rows.students=[{id:id(5),name:'مُحَمَّد',ownerId:'guest:'+id(2)}];
rows.certificateIssuers=[{id:id(6),issuerKey:'guest:'+id(2),issuerNumber:1,displayName:'ذَكَاءُ الله'}];
rows.certificateRegistrations=[{id:id(7),reservationKey:id(4)+'|guest:'+id(2)+'|2026|02',certificateId:id(4),issuerKey:'guest:'+id(2),year:'2026',riwayahCode:'02',registrationNumber:'0126-0201',reservationOrder:7}];
rows.additionalShaykhExtensions=[{id:id(8),shaykhId:id(2),mutoonJson:JSON.stringify([{introductionId:id(9)}])}];
rows.mutoonTextTemplates=[{id:id(9),name:'مقدمة',body:'النص'}];
const context={user:{id:'account',email:'admin@example.test'}};
const {backup}=await endpoint.execute({input:{action:'export'},context});
assert.deepEqual(Object.keys(backup.tables).sort(),[...BACKUP_TABLES].sort());
const same=await endpoint.execute({input:{action:'preview',backup},context});
assert.ok(same.stats.every((s:any)=>!s.missing&&!s.conflicts));
for(const t of BACKUP_TABLES)if(t!=='appUsers')rows[t]=[];
await endpoint.execute({input:{action:'restore',backup,mode:'addMissing'},context});
const guest=rows.additionalShaykhs[0],cert=rows.certificates[0],sanad=rows.asaneed[0];
assert.notEqual(guest.id,id(2));
assert.equal(cert.additionalShaykh,guest.id);
assert.deepEqual(cert.sanad,[sanad.id]);
assert.equal(rows.students[0].ownerId,'guest:'+guest.id);
assert.equal(rows.certificateIssuers[0].issuerCode,'01');
assert.equal(rows.certificateRegistrations[0].sequenceOrder,7);
assert.equal(rows.certificateRegistrations[0].registrationNumber,'0126-0201');
assert.equal(rows.certificateRegistrations[0].certificateId,cert.id);
assert.ok(rows.certificateRegistrations[0].reservationKey.includes(cert.id));
assert.equal(JSON.parse(rows.additionalShaykhExtensions[0].mutoonJson)[0].introductionId,rows.mutoonTextTemplates[0].id);
operations.length=0;
await endpoint.execute({input:{action:'restore',mode:'restore',confirmOverwrite:true,backup:{...backup,schemaVersion:2,tables:{students:[]}}},context});
assert.ok(operations.every(o=>o.table==='students'));
assert.equal(rows.certificates.length,1);
assert.equal(rows.certificateIssuers[0].issuerCode,'01');
console.log('PASS backup: complete coverage, no-op preview, remapped linked IDs and JSON, stable issuer code/order, incomplete old backup protection.');
